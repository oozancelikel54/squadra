export const dictionaries = { tr, en };

export function translate(locale, key, vars = {}) {
  const dict = dictionaries[locale] || dictionaries[DEFAULT_LOCALE];
  let text = dict[key] ?? dictionaries[DEFAULT_LOCALE][key] ?? key;
  Object.entries(vars).forEach(([k, v]) => {
    text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  });
  return text;
}

export function localizeInstruction(item, locale) {
  if (!item) return null;
  return {
    ...item,
    title: translate(locale, `inst.${item.id}.title`),
    short: translate(locale, `inst.${item.id}.short`),
    description: translate(locale, `inst.${item.id}.desc`),
  };
}
